 const context={auth:{uid:'test-customer',token:{email:'fixture@example.test'}}};
 const data={submissionId:'12345678-1234-1234-1234-123456789012',termsAccepted:true,termsVersion:'2026-10-25',pickup:'Oxford',destination:'Stansted Airport',dateTime:'2026-11-16T06:00:00Z',vehicleType:'standard',paymentMethod:'cash',marketingAttribution:attribution};
 const [a,b]=await Promise.all([createCustomerBooking.run(data,context),createCustomerBooking.run({...data,marketingAttribution:{...attribution,consentAt:now+1}},context)]);
