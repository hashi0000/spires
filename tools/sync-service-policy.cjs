const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');

const policy = JSON.parse(fs.readFileSync(path.join(root, 'service-policy.json'), 'utf8'));
const labels = JSON.parse(fs.readFileSync(path.join(root, 'customer-facing-labels.json'), 'utf8'));

const policyFolders = [
  'functions/src',
  'functions/lib',
  'customer-app/src',
  'customer-app/src/generatedDocuments',
  'spires-admin-fresh/src/data',
  'spires-admin-fresh/src/generatedDocuments',
];

for (const folder of policyFolders) {
  const dir = path.join(root, folder);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'servicePolicy.json'), JSON.stringify(policy, null, 2) + '\n');
}

fs.writeFileSync(
  path.join(root, 'spires-website/js/service-policy.js'),
  '// Generated by tools/sync-service-policy.cjs.\nwindow.SpiresServicePolicy = ' + JSON.stringify(policy, null, 2) + ';\n'
);

const labelFolders = [
  'functions/src',
  'customer-app/src',
  'spires-admin-fresh/src/data',
];

for (const folder of labelFolders) {
  const dir = path.join(root, folder);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'customerFacingLabels.json'), JSON.stringify(labels, null, 2) + '\n');
}

fs.writeFileSync(
  path.join(root, 'spires-website/js/customer-facing-labels.js'),
  '// Generated by tools/sync-service-policy.cjs.\nwindow.SpiresCustomerLabels = ' + JSON.stringify(labels, null, 2) + ';\n'
);

console.log('Synced service-policy.json and customer-facing-labels.json to app copies.');
