const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const policy = JSON.parse(fs.readFileSync(path.join(root, 'service-policy.json'), 'utf8'));
for (const folder of ['functions/src', 'customer-app/src', 'spires-admin-fresh/src/data']) {
  fs.mkdirSync(path.join(root, folder), { recursive: true });
  fs.writeFileSync(path.join(root, folder, 'servicePolicy.json'), JSON.stringify(policy, null, 2) + '\n');
}
fs.writeFileSync(path.join(root, 'spires-website/js/service-policy.js'), '// Generated by tools/sync-service-policy.cjs.\nwindow.SpiresServicePolicy = ' + JSON.stringify(policy, null, 2) + ';\n');
