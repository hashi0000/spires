const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
if (!/^127\.0\.0\.1:\d+$/.test(process.env.FIRESTORE_EMULATOR_HOST || '')) throw new Error('A local Firestore emulator is required.');
process.env.GCLOUD_PROJECT = 'demo-spires-admin';
const admin = require('../functions/node_modules/firebase-admin');
admin.initializeApp({ projectId: 'demo-spires-admin' });
const db = admin.firestore();
db.settings({ ignoreUndefinedProperties: true });
admin.auth().createCustomToken = async () => 'synthetic-token-no-real-auth';
const { manageDriverAccess, unlockDriverJobs } = require('../functions/lib/driverAccess');
const { listDriverTrips, driverTripAction } = require('../functions/lib/driverTrips');
const { cotswoldsRequest } = require('../functions/lib/cotswoldsPolicy');
const { shouldSendConfirmation } = require('../functions/lib/quotes/quoteWorkflow');
const prefix = 'synthetic-' + randomUUID();
const driver = prefix + '-driver';
const other = prefix + '-other';
const office = { auth: { uid: prefix + '-office', token: { email: 'hashim@spires.com' } } };
const denied = promise => assert.rejects(promise);
async function main() {
  await db.collection('drivers').doc(driver).set({ active: true, name: 'Synthetic Driver' });
  await db.collection('drivers').doc(other).set({ active: true, name: 'Other Synthetic' });
  await denied(manageDriverAccess.run({ driverId: driver, action: 'reset' }, { auth: null }));
  const access = await manageDriverAccess.run({ driverId: driver, action: 'reset' }, office);
  assert.match(access.code, /^\d{4}$/);
  const activation = await unlockDriverJobs.run({ pin: access.code }, { rawRequest: { ip: '127.0.0.98' } });
  assert.equal(activation.token, 'synthetic-token-no-real-auth');
  await denied(unlockDriverJobs.run({ pin: access.code }, { rawRequest: { ip: '127.0.0.98' } }));
  const generation = (await db.collection('driverAccess').doc(driver).get()).data().generation;
  const context = { auth: { uid: prefix + '-session', token: { driverJobs: true } } };
  await db.collection('driverSessions').doc(context.auth.uid).set({ enabled: true, driverId: driver, generation });
  const ownId = prefix + '-own';
  const otherId = prefix + '-other-booking';
  const splitId = prefix + '-split';
  const booking = { status: 'confirmed', revision: 0, driverId: driver, actualFare: 180,
    amountReceivedPence: 5000, paymentStatus: 'partial', hirerName: 'Synthetic Passenger',
    hirerEmail: 'synthetic@example.invalid', hirerPhone: '07700900000', pickupLocation: 'Oxford', destination: 'Oxford',
    quoteToken: 'must-not-be-returned', timedHire: { startAt: '2026-11-15T10:00:00Z', includedMinutes: 240,
      itinerary: 'Synthetic stops, final Oxford', extraRatePounds: 10, extraIntervalMinutes: 20 } };
  await db.collection('bookings').doc(ownId).set(booking);
  await db.collection('bookings').doc(otherId).set({ ...booking, driverId: other });
  await db.collection('bookings').doc(splitId).set({ ...booking, timedHire: null, driverId: other, returnDriverId: driver, bookingType: 'return', returnPickupLocation: 'Return only', returnDestination: 'Oxford', pickupLocation: 'Other driver private route' });
  const listed = await listDriverTrips.run({}, context);
  assert.equal(listed.bookings.length, 2);
  assert.equal(listed.bookings.find(row => row.id === ownId).quoteToken, undefined);
  assert.equal(listed.bookings.find(row => row.id === splitId).pickupLocation, undefined);
  assert.deepEqual(listed.bookings.find(row => row.id === splitId).assignedLegs, ['return']);
  const action = (body, id = ownId) => driverTripAction.run({ bookingId: id, leg: 'outbound', requestId: randomUUID(), ...body }, context);
  await denied(action({ action: 'complete', expectedRevision: 0, at: '2026-11-15T14:00:00Z' }, otherId));
  await denied(action({ action: 'complete', expectedRevision: 0, at: '2026-11-15T14:00:00Z' }, splitId));
  await action({ action: 'driver_ready', at: '2026-11-15T10:00:00Z', expectedRevision: 0 });
  await denied(action({ action: 'complete', at: '2026-11-15T14:21:00Z', expectedRevision: 0 }));
  await action({ action: 'complete', at: '2026-11-15T14:21:00Z', expectedRevision: 1 });
  const before = (await db.collection('bookings').doc(ownId).get()).data();
  assert.equal(before.status, 'completed');
  assert.equal(before.paymentStatus, 'partial');
  assert.equal(shouldSendConfirmation(booking, before), false);
  await action({ action: 'finalise', expectedRevision: 2 });
  const extra = (await db.collection('bookings').doc(ownId).get()).data();
  assert.equal(extra.additionalCharges[0].amountPence, 2000);
  assert.equal(extra.outstandingPence, 15000);
  await denied(action({ action: 'finalise', expectedRevision: 3 }));
  const requestId = randomUUID();
  const payment = { action: 'payment', amountPence: 15000, method: 'cash', expectedRevision: 3, requestId };
  await action(payment);
  const repeated = await action(payment);
  assert.equal(repeated.duplicate, true);
  const paid = (await db.collection('bookings').doc(ownId).get()).data();
  assert.equal(paid.amountReceivedPence, 20000);
  assert.equal(paid.paymentEntries.length, 1);
  assert.equal(paid.paymentStatus, 'paid');
  assert.equal(paid.actualFare, 180);
  assert.equal(paid.pickupLocation, 'Oxford');
  const jobs = await db.collection('emailJobs').where('bookingId', '==', ownId).get();
  assert.equal(jobs.size, 1);
  const quote = cotswoldsRequest({ journeyType: 'cotswolds', hireHours: 6, hireItinerary: 'Stops and final Oxford', timedHireAccepted: true, extraRatePounds: 0 }, '2027-06-01T10:00', 'executive', Date.now());
  assert.equal(quote.ok, true);
  assert.equal(quote.fields.proposedFarePounds, 350);
  assert.equal(quote.fields.timedHire.extraRatePounds, 10);
  assert.equal(quote.fields.timedHire.startAt, '2027-06-01T09:00:00.000Z');
  await manageDriverAccess.run({ driverId: driver, action: 'revoke' }, office);
  await denied(listDriverTrips.run({}, context));
  await denied(driverTripAction.run({ bookingId: ownId, leg: 'outbound', requestId: randomUUID(), action: 'payment', amountPence: 1, expectedRevision: 4 }, context));
  console.log('PASS: driver privacy, per-leg permissions, revisions, completion silence, time charges, deposit balance, payment retry, receipt queue, DST pricing, session revocation. No real messages or payments.');
}
main().then(() => admin.app().delete()).catch(error => { console.error(error); process.exitCode = 1; });
